#!/usr/bin/env python3
"""
Write robohub-stm32's module.yml from the data it indexes.

The manifest is a platform's identity card: it says what the platform is, what it
needs, and which presets it provides. It was being edited by hand and by script
at the same time, and a manifest edited that way accumulates descriptions whose
continuation lines no longer belong to anything — which is a file that describes
nothing, read as a crash.

So it is written from the data, the same way the presets and the target specs
are. The preset files are the source of what a preset is; this writes the index
that points at them. Nothing here is hand-maintained and nothing here can drift
from the files it names, because it is generated from them.

    python3 tools/gen_manifest.py

SPDX-License-Identifier: MIT
"""

import json
import pathlib
import textwrap

ROOT = pathlib.Path(__file__).resolve().parent.parent

PREAMBLE = '''#
# robohub-stm32 — the STM32 platform for the RoboHub Platform.
#
# This module implements the platform-independent interfaces declared by
# robohub-common against STMicroelectronics' STM32 HAL and CMSIS, and carries a
# board support package for each supported development board.
#
# THIS FILE IS GENERATED by tools/gen_manifest.py from the preset files it
# indexes. Edit those, not this: a manifest edited by hand and a manifest written
# by a script are two manifests, and the one that is read is whichever one
# happens to be on disk.
#
# SPDX-License-Identifier: MIT
#

module:
  name: robohub-stm32
  type: platform
  version: 0.1.0
  description: >
    STM32 platform for the RoboHub Platform. Implements the RoboHub HAL
    interfaces and the platform initialisation contract on top of the STM32 HAL
    and CMSIS, and carries a board support package for each supported board.

  maintainer: "Aurel Miron"
  license: "MIT"
  created: "2026-09-30"

# No main: a platform is native code a project links, not something it runs.

build:
  language: c
  standard: c11

  # Every directory a consumer needs on its include path, declared here so that a
  # build reads them rather than being told them.
  #
  # `include/` is for the headers a program includes by their own name, and
  # `include/robohub/hal/` for the interfaces, which are included as `gpio.h`
  # rather than as `robohub/hal/gpio.h`. The two answer to different names, so
  # they are separate directories and a build needs both.
  include_dirs:
    - include/
    - include/robohub/
    - include/robohub/hal/
    - include/robohub/platform/
    - include/robohub/drivers/
    - platform/
    - vendor/
    - ${CMAKE_BINARY_DIR}/generated/

  # No source_dirs: every source is named below.
  #
  # A directory scan compiles whatever is in the folder, which means a driver
  # written for a peripheral this program does not use is compiled anyway, and a
  # build grows a source nobody chose. It also makes a driver that does not compile
  # for this part a build that will not compile at all, because the file is in the
  # folder whether or not it belongs here. Naming is the only way "this build does
  # not use that driver" is something a file can say.

  sources:
    - src/error.c
    - src/platform/stm32_error.c
    - src/platform/stm32_clock.c
    - src/platform/stm32_console.c
    - src/platform/stm32_platform.c
    - src/hal/stm32_gpio.c
    - src/hal/stm32_i2c.c
    - src/hal/stm32_spi.c
    - src/hal/stm32_uart.c
    - src/hal/stm32_rs485.c
    - src/hal/stm32_timer.c

package:
  kind: library
  # A C library has no binary to build. Without this the packer assumes a
  # component layout and runs `go build`, which fails on a module with no
  # go.mod.
  binary: false
  include:
    - module.yml
    - README.md
    - CMakeLists.txt
    - include
    - src
    - platform
    - boards
    - presets
    - targets
    - kconfig
    - cmake
  require:
    - module.yml
    - CMakeLists.txt
    - include
    - src
    - platform
    - presets
    - targets

# The interfaces this platform implements.
#
# It is a dependency like any other, and declaring it here is what puts its
# headers on the include path of everything this platform builds — so a program
# that uses only this platform's API does not have to name robohub-common
# itself, and one that does name it is saying it uses those headers directly.
#
# `path` is where robohub-common is on the machine this was written on and is
# tried first; `git` is where it is for anyone else.
depends:
  - name: robohub-common
    type: c
    path: /home/miraur/projects/robohub-common
    git: https://github.com/RoboHubPlatform/robohub-common
    branch: main

  # The vendor's HAL and CMSIS, fetched by a preset rather than named here: a
  # build brings the ones its preset names, and a checkout does not carry them.
  # The paths below are where a fetched preset's repositories are assembled.

config:
  # Where the target specs live, and where the presets live. A build is handed
  # these rather than finding them: a build that went looking for a `targets/`
  # directory in a repository would be working out what a module offers by
  # looking at its file layout.
  targets: targets
  presets: presets

  # The bare-metal build resolves through the `linux` dialect, which writes
  # `.config` and `include/generated/autoconf.h`.
  #
  # Only the symbols this platform owns are declared. The RH_HAL_* symbols belong
  # to robohub-common, which owns the interfaces: a project that depends on both
  # would otherwise have two fragments defining the same symbol, and which
  # definition won would depend on the order they were merged in.
  dialect: linux
  kconfig_fragments:
    - Kconfig

metadata:
  tags:
    - platform
    - stm32
    - hal
    - cmsis
    - embedded
    - baremetal
  stability: experimental
  visibility: public
'''


def wrap(text, indent, width=74):
    """Wrap a sentence into a YAML block scalar, quoted on one line if it fits."""
    if not text:
        return '""'
    flat = " ".join(text.split())
    if len(flat) + len(indent) + 2 <= width:
        return '"%s"' % flat.replace('"', "'")
    body = textwrap.wrap(flat, width=width - len(indent) - 2)
    return ">-\n" + "\n".join(indent + "  " + line for line in body)


def preset_declarations():
    """One declaration per preset file, families first and then boards.

    A preset is declared rather than discovered: a build must be able to say what
    this platform offers by reading its manifest, without looking at what files
    happen to be lying beside it.
    """
    families, boards = [], []
    for path in sorted((ROOT / "presets").glob("*.json")):
        if path.name == "families.json":
            continue
        data = json.load(open(path))
        if data.get("board"):
            boards.append((path, data))
        else:
            families.append((path, data))

    out = ["""
# ---------------------------------------------------------------------------
#  What this platform provides
# ---------------------------------------------------------------------------
#
# The presets a build may ask this platform for. A preset is a fact about a
# piece of hardware, and it is written in a file beside this manifest: the
# repositories and the revisions, the directories of them that go on the include
# path, and the hardware they are for. This is the index, so that a list of what
# is on offer is a list rather than a wall.
#
# `target` is the target spec that builds each preset. A preset says what to
# fetch and a target says how, and the two name each other so a mismatch is a
# disagreement between two files rather than a build that quietly used the wrong
# one.

presets:
"""]

    for path, data in families:
        out.append('    - name: "%s"' % data["name"])
        out.append("      description: %s" % wrap(data.get("description", ""), "      "))
        out.append('      core: "%s"' % data.get("core", ""))
        out.append('      file: "%s"' % path.relative_to(ROOT).as_posix())
        out.append('      target: "%s"' % data.get("target", data["name"]))
        out.append("")

    out.append("  # The boards. Each names the family preset whose sources it builds and")
    out.append("  # the target that links it, so a program written for a board says so")
    out.append("  # once and the build works out both halves from that.")
    out.append("")
    for path, data in boards:
        out.append('    - name: "%s"' % data["name"])
        out.append("      description: %s" % wrap(data.get("description", ""), "      "))
        out.append('      file: "%s"' % path.relative_to(ROOT).as_posix())
        out.append('      target: "%s"' % data.get("target", data["name"]))
        out.append("")

    return "\n".join(out)


def main():
    manifest = PREAMBLE.rstrip() + "\n" + preset_declarations()
    path = ROOT / "module.yml"
    path.write_text(manifest)

    count = manifest.count('    - name: "')
    print("wrote module.yml with %d presets declared" % count)


if __name__ == "__main__":
    main()