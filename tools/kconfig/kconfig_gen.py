#!/usr/bin/env python3

import argparse
import re
import sys

# Usage:
#   python kconfig_gen.py <input1> <input2> ... <output>
#
# Example:
#   python kconfig_gen.py Kconfig.gpio Kconfig.i2c kconfig.h

def parse_kconfig_file(path):
    configs = {}
    current = None

    with open(path, "r") as f:
        for line in f:
            line = line.strip()

            # Detect "config NAME"
            if line.startswith("config "):
                current = line.split()[1]
                continue

            # Detect "default y/n"
            if current and line.startswith("default"):
                val = line.split()[1].lower()
                configs[current] = 1 if val == "y" else 0
                current = None

    return configs


def parse_config_file(path):
    configs = {}
    assignment = re.compile(r"^CONFIG_([A-Za-z0-9_]+)=(y|n)$")

    with open(path, "r", encoding="utf-8") as config_file:
        for line in config_file:
            line = line.strip()
            match = assignment.match(line)
            if match:
                configs[match.group(1)] = 1 if match.group(2) == "y" else 0

    return configs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", help="application configuration override file")
    parser.add_argument("paths", nargs="+", help="Kconfig inputs followed by output")
    args = parser.parse_args()

    if len(args.paths) < 2:
        parser.error("provide at least one input file and an output file")

    input_files = args.paths[:-1]
    output_file = args.paths[-1]

    all_configs = {}

    # Parse all Kconfig fragments
    for path in input_files:
        cfg = parse_kconfig_file(path)
        all_configs.update(cfg)

    if args.config:
        all_configs.update(parse_config_file(args.config))

    # Generate kconfig.h
    with open(output_file, "w", encoding="utf-8") as out:
        out.write("/* Auto-generated by kconfig_gen.py */\n\n")
        for key, val in all_configs.items():
            out.write(f"#define CONFIG_{key} {val}\n")

    print(f"Generated {output_file} with {len(all_configs)} config entries.")


if __name__ == "__main__":
    main()
